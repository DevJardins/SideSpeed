val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun signingValue(propKey: String, envKey: String): String? =
    keystoreProps.getProperty(propKey) ?: System.getenv(envKey)

/** The bar from the translations plan: the TV app ships every language at or above this share of English. */
val LANGUAGE_BAR = 0.70

/**
 * Evaluated at configuration time so the log and the locale filters always describe the
 * checked-in translations. The generator task below re-evaluates the same inputs at
 * execution time with up-to-date checking.
 */
val gateResult = LanguageGate.evaluate(
    file("src/main/res/values/strings.xml"),
    file("src/main/res"),
    LANGUAGE_BAR,
).also { logger.lifecycle(LanguageGate.summary("app", it, LANGUAGE_BAR)) }

/** Writes ShippedLanguages.kt, locales_config.xml and the tags the unit test pins them to. */
abstract class GenerateShippedLanguages : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val resDir: DirectoryProperty

    @get:Input
    abstract val bar: Property<Double>

    @get:OutputDirectory
    abstract val kotlinOutDir: DirectoryProperty

    @get:OutputDirectory
    abstract val resOutDir: DirectoryProperty

    @get:OutputFile
    abstract val expectedTagsFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val result = LanguageGate.evaluate(
            resDir.get().asFile.resolve("values/strings.xml"),
            resDir.get().asFile,
            bar.get(),
        )
        val tags = result.included.map { it.tag }
        val pkgDir = kotlinOutDir.get().asFile.resolve("io/github/devjardins/sidespeed/l10n")
        pkgDir.mkdirs()
        pkgDir.resolve("ShippedLanguages.kt").writeText(
            "package io.github.devjardins.sidespeed.l10n\n\n" +
                "// Generated by generateShippedLanguages from the language gate; do not edit.\n" +
                "object ShippedLanguages {\n" +
                "    val TAGS: List<String> = listOf(${tags.joinToString(", ") { "\"$it\"" }})\n" +
                "}\n",
        )
        val xmlDir = resOutDir.get().asFile.resolve("xml")
        xmlDir.mkdirs()
        val locales = listOf("en") + tags
        xmlDir.resolve("locales_config.xml").writeText(
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" +
                "<locale-config xmlns:android=\"http://schemas.android.com/apk/res/android\">\n" +
                locales.joinToString("\n") { "    <locale android:name=\"$it\" />" } + "\n" +
                "</locale-config>\n",
        )
        expectedTagsFile.get().asFile.apply {
            parentFile.mkdirs()
            writeText(if (tags.isEmpty()) "" else tags.joinToString("\n", postfix = "\n"))
        }
    }
}

val generateShippedLanguages = tasks.register<GenerateShippedLanguages>("generateShippedLanguages") {
    resDir.set(file("src/main/res"))
    bar.set(LANGUAGE_BAR)
    kotlinOutDir.set(layout.buildDirectory.dir("generated/l10n/kotlin"))
    resOutDir.set(layout.buildDirectory.dir("generated/l10n/res"))
    expectedTagsFile.set(layout.buildDirectory.file("generated/l10n/expectedTags.txt"))
}

// AGP 9 removed the Provider/File overloads of addGeneratedSourceDirectory, so the typed
// task above wires each output directory to the variant sources that consume it.
androidComponents {
    onVariants { variant ->
        variant.sources.kotlin?.addGeneratedSourceDirectory(
            generateShippedLanguages,
            GenerateShippedLanguages::kotlinOutDir,
        )
        variant.sources.res?.addGeneratedSourceDirectory(
            generateShippedLanguages,
            GenerateShippedLanguages::resOutDir,
        )
    }    // Pseudo-locales are on only in debug, so only debug keeps their resources.
    onVariants(selector().withBuildType("debug")) { variant ->
        variant.androidResources.localeFilters.addAll(LanguageGate.PSEUDO_LOCALE_FILTERS)
    }
}

android {
    namespace = "io.github.devjardins.sidespeed"
    compileSdk = 36

    defaultConfig {
        applicationId = "io.github.devjardins.sidespeed"
        minSdk = 24
        targetSdk = 36
        // Single source: derived from sidespeed.versionName by the root build script (0.7.0 -> 700).
        versionCode = rootProject.extra["sidespeedVersionCode"] as Int
        versionName = providers.gradleProperty("sidespeed.versionName").get()
        buildConfigField("String", "UPDATE_BASE_URL", "\"https://github.com/DevJardins/SideSpeed/releases/download\"")
        buildConfigField("String", "APP_UPDATES_URL", "\"https://sidespeed.app/updates-v2.json\"")
    }

    signingConfigs {
        // Only created when a keystore is supplied; otherwise the release APK stays unsigned.
        val storeFile = signingValue("storeFile", "SIDESPEED_KEYSTORE")
        if (storeFile != null) {
            create("release") {
                this.storeFile = rootProject.file(storeFile)
                storePassword = signingValue("storePassword", "SIDESPEED_KEYSTORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "SIDESPEED_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "SIDESPEED_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        // Debug serves updates from -PupdateBaseUrl (the emulator E2E); release is always GitHub.
        debug {
            isPseudoLocalesEnabled = true
            val base = (findProperty("updateBaseUrl") as String?)?.takeIf { it.isNotBlank() }
                ?: "https://github.com/DevJardins/SideSpeed/releases/download"
            buildConfigField("String", "UPDATE_BASE_URL", "\"$base\"")
            // The emulator E2E serves a fixture catalog from the host loopback; release is always sidespeed.app.
            val catalog = (findProperty("appUpdatesUrl") as String?)?.takeIf { it.isNotBlank() }
                ?: "https://sidespeed.app/updates-v2.json"
            buildConfigField("String", "APP_UPDATES_URL", "\"$catalog\"")
        }
        release {
            isMinifyEnabled = true
            signingConfigs.findByName("release")?.let { signingConfig = it }
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
        // Non-debuggable but debug-key-signed, so ART AOT-compiles it and it installs over a debug
        // install without an uninstall. Used for on-device runs (baseline-profile generation and the
        // kill/restart check); never shipped.
        create("benchmark") {
            initWith(getByName("release"))
            isMinifyEnabled = false
            signingConfig = signingConfigs.getByName("debug")
            matchingFallbacks += "release"
        }
        // Same shape as benchmark, but named to match the :baselineprofile module's nonMinifiedRelease
        // test variant: without this, generation targets the unsigned release APK and cannot install.
        create("nonMinifiedRelease") {
            initWith(getByName("release"))
            isMinifyEnabled = false
            signingConfig = signingConfigs.getByName("debug")
            matchingFallbacks += "release"
        }
    }

    // Ships only English plus the languages at or above the gate; debug adds the
    // pseudo-locales below (androidComponents). The filters go straight to aapt2 -c,
    // which wants qualifier syntax (en-rXA), not BCP-47 (en-XA).
    androidResources {
        localeFilters += LanguageGate.releaseLocaleFilters(gateResult)
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

