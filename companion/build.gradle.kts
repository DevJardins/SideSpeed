/** The bar from the translations plan: the Companion ships every language at or above this share of English. */
val LANGUAGE_BAR = 0.70

/**
 * Evaluated at configuration time so the log and the filtered resources always describe
 * the checked-in translations. The generator task below re-evaluates the same inputs at
 * execution time with up-to-date checking.
 */
val gateResult = LanguageGate.evaluate(
    file("src/commonMain/composeResources/values/strings.xml"),
    file("src/commonMain/composeResources"),
    LANGUAGE_BAR,
).also { logger.lifecycle(LanguageGate.summary("companion", it, LANGUAGE_BAR)) }

/**
 * Copies the compose resources, leaving out every `values-*` folder whose language
 * is below the gate. The Compose plugin reads this copy instead of the source tree.
 */
val syncL10nComposeResources = tasks.register<Sync>("syncL10nComposeResources") {
    val kept = gateResult.included.map { it.tag }.toSet()
    val dropped = file("src/commonMain/composeResources").listFiles()
        ?.filter { it.isDirectory && it.name.startsWith("values-") }
        ?.mapNotNull { dir ->
            val tag = LanguageGate.qualifierToTag(dir.name) ?: return@mapNotNull null
            if (tag !in kept) dir.name else null
        }.orEmpty()
    inputs.property("droppedLanguageFolders", dropped.sorted())
    from(file("src/commonMain/composeResources")) {
        dropped.forEach { exclude("$it/**") }
    }
    into(layout.buildDirectory.dir("l10n/composeResources"))
}

/** Writes ShippedLanguages.kt and the tags the desktop test pins it to. */
abstract class GenerateShippedLanguages : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val resDir: DirectoryProperty

    @get:Input
    abstract val bar: Property<Double>

    @get:OutputDirectory
    abstract val kotlinOutDir: DirectoryProperty

    @get:OutputFile
    abstract val expectedTagsFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val result = LanguageGate.evaluate(
            resDir.get().asFile.resolve("values/strings.xml"),
            resDir.get().asFile,
            bar.get(),
        )
        val tags = result.included.map { it.tag }
        val pkgDir = kotlinOutDir.get().asFile.resolve("io/github/devjardins/sidespeed/companion/l10n")
        pkgDir.mkdirs()
        pkgDir.resolve("ShippedLanguages.kt").writeText(
            "package io.github.devjardins.sidespeed.companion.l10n\n\n" +
                "// Generated by generateShippedLanguages from the language gate; do not edit.\n" +
                "object ShippedLanguages {\n" +
                "    val TAGS: List<String> = listOf(${tags.joinToString(", ") { "\"$it\"" }})\n" +
                "}\n",
        )
        expectedTagsFile.get().asFile.apply {
            parentFile.mkdirs()
            writeText(if (tags.isEmpty()) "" else tags.joinToString("\n", postfix = "\n"))
        }
    }
}

val generateShippedLanguages = tasks.register<GenerateShippedLanguages>("generateShippedLanguages") {
    resDir.set(file("src/commonMain/composeResources"))
    bar.set(LANGUAGE_BAR)
    kotlinOutDir.set(layout.buildDirectory.dir("generated/l10n/kotlin"))
    expectedTagsFile.set(layout.buildDirectory.file("generated/l10n/expectedTags.txt"))
}

kotlin {
    sourceSets.named("commonMain") {
        kotlin.srcDir(generateShippedLanguages.flatMap { it.kotlinOutDir })
    }
}

tasks.matching { it.name.startsWith("compileKotlin") }.configureEach {
    dependsOn(generateShippedLanguages)
}

tasks.matching {
    it.name.startsWith("convertXmlValueResourcesFor") ||
        it.name.startsWith("copyNonXmlValueResourcesFor") ||
        it.name.startsWith("prepareComposeResourcesTaskFor")
}.configureEach {
    dependsOn(syncL10nComposeResources)
}

tasks.matching { it.name.endsWith("ComposeResourcesToAndroidAssets") }.configureEach {
    // The Compose plugin's asset-copy tasks merge into their output directory without
    // removing files that disappeared from the inputs, so a language dropping below the
    // bar would otherwise keep shipping in incremental builds (the XML converter and the
    // desktop assembler wipe their outputs; this task does not). Track the filtered
    // resources so every gate change re-runs the copy, and start from an empty output
    // directory so removed languages actually disappear.
    inputs.dir(syncL10nComposeResources.map { it.destinationDirectory })
        .withPropertyName("l10nFilteredComposeResources")
        .withPathSensitivity(PathSensitivity.RELATIVE)
    doFirst { project.delete(outputs.files) }
}

